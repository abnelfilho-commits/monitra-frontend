const assert = require('node:assert/strict');
const {chromium} = require(process.env.PLAYWRIGHT_MODULE || 'playwright');
const FRONT = process.env.PESSOAS_FRONT_URL || 'http://127.0.0.1:5186';
(async () => {
 const browser = await chromium.launch({channel:'chrome',headless:true});
 try {
  const page = await browser.newPage({viewport:{width:1440,height:800}});
  page.setDefaultTimeout(12000);
  page.setDefaultNavigationTimeout(60000);
  const calls=[], errors=[];
  page.on('pageerror',e=>errors.push(e.message));
  await page.route('**/*',route=>{
   const r=route.request(),u=new URL(r.url());
   if(u.origin===FRONT)return route.continue();
   calls.push({path:u.pathname,method:r.method()});
   const reply=(body,status=200)=>route.fulfill({status,contentType:'application/json',body:JSON.stringify(body)});
   if(u.pathname==='/auth/login')return reply({access_token:'synthetic-only'});
   if(u.pathname==='/me')return reply({id:99,perfil:'ADMIN',nome:'Teste',modulos:[]});
   if(u.pathname==='/saude-mental/cockpit/gestao')return reply({},403);
   if(u.pathname==='/admin/pessoas/')return reply(Array.from({length:20},(_,i)=>({id:i+1,nome_completo:`Pessoa sintética ${i+1}`,ativo:true})));
   if(u.pathname==='/admin/instituicoes/')return reply([]);
   if(u.pathname.startsWith('/formularios/codigo/'))return reply({campos:[]});
   return reply([]);
  });
  await page.goto(FRONT+'/admin/pessoas');
  await page.waitForURL('**/login');
  assert.equal(calls.filter(c=>c.path==='/admin/pessoas/').length,0);
  await page.locator('input[type=email]').fill('synthetic@example.invalid');
  await page.locator('input[type=password]').fill('synthetic-test-only');
  await page.getByRole('button',{name:'Entrar',exact:true}).click();
  await page.waitForURL('**/plataforma');
  await page.getByRole('heading',{name:'Linhas de cuidado',exact:true}).waitFor();
  assert.equal(calls.filter(c=>c.method==='POST').length,1);
  await page.goto(FRONT+'/admin/pessoas?demo=1');
  await page.getByRole('button',{name:'Consultar',exact:true}).first().waitFor();
  await page.waitForLoadState('networkidle');
  const meBefore=calls.filter(c=>c.path==='/me').length;
  const managementBefore=calls.filter(c=>c.path==='/saude-mental/cockpit/gestao').length;
  const lengthBefore=await page.evaluate(()=>history.length);
  await page.evaluate(()=>window.scrollTo(0,450));
  await page.waitForFunction(()=>Number(sessionStorage.getItem('scroll:/admin/pessoas'))>100);
  const saved=await page.evaluate(()=>Number(sessionStorage.getItem('scroll:/admin/pessoas')));
  // HTMLElement.click avoids scrolling the sidebar into view before navigation.
  await page.getByRole('navigation',{name:'Navegação institucional'}).getByRole('link',{name:'Instituições',exact:true}).evaluate(e=>e.click());
  await page.waitForURL('**/admin/instituicoes');
  await page.getByRole('heading',{name:'Instituições',exact:true}).waitFor();
  await page.waitForFunction(()=>scrollY===0);
  await page.goBack();
  await page.waitForURL('**/admin/pessoas?demo=1');
  await page.getByRole('button',{name:'Consultar',exact:true}).first().waitFor();
  await page.waitForLoadState("networkidle");
  const restored = await page.evaluate(()=>scrollY);
  await page.goForward();
  await page.waitForURL('**/admin/instituicoes');
  await page.getByRole('heading',{name:'Instituições',exact:true}).waitFor();
  await page.waitForLoadState('networkidle');
  assert.equal(await page.evaluate(()=>history.length),lengthBefore+1);
  assert.equal(calls.filter(c=>c.path==='/me').length,meBefore,'AuthProvider remounted on internal navigation');
  assert.equal(calls.filter(c=>c.path==='/saude-mental/cockpit/gestao').length,managementBefore,'Administrative layout remounted on sibling navigation');
  assert.equal(calls.filter(c=>c.method!=='GET').length,1,'Navigation introduced writes');
  await page.getByRole('button',{name:'Sair',exact:true}).click();
  await page.waitForURL('**/login');
  assert.equal(await page.evaluate(()=>localStorage.getItem('access_token')),null);
  await page.goto(FRONT+'/not-a-real-route'); await page.waitForURL('**/login');
  await page.goto(FRONT+'/'); await page.waitForURL('**/login');
  await page.goto(FRONT+'/avaliacoes/MCHAT?pacienteId=0&care_line=1');
  await page.getByRole('heading',{name:'M-CHAT',exact:true}).waitFor();
  assert.equal(new URL(page.url()).search,'?pacienteId=0&care_line=1');
  assert.deepEqual(errors,[]);
  console.log('SCROLL_POP', JSON.stringify({saved,restored}));
  console.log('ROUTER_PROVIDER navigation checks completed: real App/StrictMode, anonymous guard, login/platform, authenticated reload, sibling layout/session stability, query, POP back/forward/scroll, history length, logout, public assessment, root/fallback, no navigation writes.');
  assert.ok(Math.abs(restored-saved)<5, `POP scroll mismatch: saved=${saved}, restored=${restored}`);
 } finally { await browser.close(); }
})().catch(e=>{console.error(e);process.exitCode=1;});
